#!/bin/bash
#
# Generate the vendor makefiles from the files under vendor/xiaomi/aries.
#
#   ./setup-makefiles.sh        # use the paths listed in proprietary-blobs.txt
#   ./setup-makefiles.sh -a     # use every file present in proprietary/
#
set -eu

DEVICE=aries
VENDOR=xiaomi

BASE=$(cd "$(dirname "$0")" && pwd)
TOP=$(cd "$BASE/../../.." && pwd)
VENDOR_DIR="$TOP/vendor/$VENDOR/$DEVICE"
PROPRIETARY="$VENDOR_DIR/proprietary"

if [ ! -d "$PROPRIETARY" ]; then
    echo "error: $PROPRIETARY is missing, run extract-files.sh first" >&2
    exit 1
fi

if [ "${1:-}" = "-a" ]; then
    LIST=$(cd "$PROPRIETARY" && find . -type f | sed 's|^\./||' | sort -u)
else
    LIST=$(sed -e 's/#.*//' -e 's/[[:space:]]*$//' -e '/^[[:space:]]*$/d' \
               "$BASE/proprietary-blobs.txt" | awk -F: '{print $NF}' | sort -u)
fi

mkdir -p "$VENDOR_DIR"

BLOBS_MK="$VENDOR_DIR/aries-vendor-blobs.mk"
{
    echo "# Generated by device/$VENDOR/$DEVICE/setup-makefiles.sh. Do not edit."
    echo
    echo "PRODUCT_COPY_FILES += \\"
} > "$BLOBS_MK"

COUNT=0
while IFS= read -r f; do
    [ -n "$f" ] || continue
    [ -f "$PROPRIETARY/$f" ] || continue
    echo "    vendor/$VENDOR/$DEVICE/proprietary/$f:system/$f \\" >> "$BLOBS_MK"
    COUNT=$((COUNT + 1))
done <<< "$LIST"

# Drop the trailing backslash of the last entry.
sed -i '$ s/[[:space:]]*\\$//' "$BLOBS_MK"

if [ "$COUNT" -eq 0 ]; then
    echo "warning: no files found under $PROPRIETARY" >&2
fi

cat > "$VENDOR_DIR/aries-vendor.mk" <<'EOF'
# Generated by device/xiaomi/aries/setup-makefiles.sh. Do not edit.

$(call inherit-product, vendor/xiaomi/aries/aries-vendor-blobs.mk)
EOF

cat > "$VENDOR_DIR/BoardConfigVendor.mk" <<'EOF'
# Generated by device/xiaomi/aries/setup-makefiles.sh. Do not edit.
EOF

echo "generated $VENDOR_DIR/aries-vendor{,-blobs}.mk and BoardConfigVendor.mk ($COUNT files)"
